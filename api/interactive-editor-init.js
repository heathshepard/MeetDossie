// Phase 1 Interactive Form Editor — TREC 20-19 branch.
// -----------------------------------------------------------------------
// Returns a rich metadata layer for the ~200 agent-fillable fields on
// TREC 20-19 grouped into progressive-disclosure sections. Data comes from
// the cached Fable5 auto-map run + the current transactions row.
//
// Response shape (differs from the legacy 4-form response):
//   {
//     ok: true,
//     formNumber: '20-19',
//     templateId: '4996863',
//     trecEffectiveDate: 'YYYY-MM-DD' | null,
//     trecFormNumber: '20-19',
//     versionLabel: 'TREC 20-19 · Effective 07/01/2026',
//     transaction: { id, buyer_name, seller_name, property_address, role },
//     pageCount: 12,
//     pdfUrl: <signed URL to the current filled PDF or data URL to blank>,
//     documentId: <uuid | null>,
//     sections: [
//       { id, title, heading, description, defaultOpen, fields: [...] },
//       ...
//     ],
//     totals: { total, required, filled, missing },
//     unmappedCount: 0
//   }
async function handlePhase1Init({ req, res, userId, transactionId }) {
  // 1. Fetch the transaction row (ownership check).
  const txnRows = await supabaseCall('GET', `transactions?id=eq.${transactionId}&limit=1`);
  if (!txnRows || txnRows.length === 0) {
    return res.status(404).json({ ok: false, error: 'Transaction not found.' });
  }
  const txn = txnRows[0];
  if (txn.user_id !== userId) {
    return res.status(403).json({ ok: false, error: 'Forbidden.' });
  }

  // 2. Load the cached Fable5 field map for TREC 20-19.
  const runRows = await supabaseCall(
    'GET',
    `dossiesign_auto_map_runs?id=eq.${TREC_20_19_FABLE5_RUN_ID}&select=id,fields,field_count,page_count`
  );
  if (!runRows || runRows.length === 0) {
    return res.status(500).json({
      ok: false,
      error: 'TREC 20-19 field map not found. Contact support.',
    });
  }
  const runRow = runRows[0];
  const fable5Fields = Array.isArray(runRow.fields) ? runRow.fields : [];

  // 3. Enrich each Fable5 row with editor metadata + current transactions value.
  //    Skip signer widgets (signature/initial) — DocuSeal places those.
  //    Track unmapped-to-editor counts for transparency (never silently hide).
  //
  // 2026-07-13 CARTER — Bug #2 (Quinn DoD Round 1). Non-canonical fields now
  // live in transactions.contract_field_drafts['20-19'] so they survive
  // reloads. Precedence: draft (last user edit) > canonical column > blank.
  const draftsForForm = (txn.contract_field_drafts && typeof txn.contract_field_drafts === 'object')
    ? (txn.contract_field_drafts['20-19'] || {})
    : {};
  const enriched = [];
  let unmappedCount = 0;
  for (const raw of fable5Fields) {
    const canonical = (raw && raw.name) || null;
    let currentValue = null;
    if (canonical && Object.prototype.hasOwnProperty.call(draftsForForm, canonical)) {
      currentValue = draftsForForm[canonical];
    } else if (canonical && Object.prototype.hasOwnProperty.call(txn, canonical)) {
      currentValue = txn[canonical];
    }
    const field = enrichFable5Field(raw, currentValue);
    if (!field) continue;
    if (field.section === 'other') unmappedCount += 1;
    enriched.push(field);
  }

  const sections = groupFieldsIntoSections(enriched);

  // 4. Compute totals for the header progress indicator.
  let total = 0;
  let required = 0;
  let filled = 0;
  let missing = 0;
  for (const f of enriched) {
    total += 1;
    if (f.required) {
      required += 1;
      if (f.value && String(f.value).trim() !== '') filled += 1;
      else missing += 1;
    }
  }

  // 5. Look up the most-recent filled document for TREC 20-19. Falls back to
  //    the blank 20-19 template PDF via the shared resolver.
  const docRows = await supabaseCall(
    'GET',
    `documents?transaction_id=eq.${transactionId}&document_type=eq.resale_contract&select=id,storage_path,file_name,status,form_template_id,created_at&order=created_at.desc&limit=1`
  );
  const doc = (docRows && docRows[0]) || null;

  let pdfUrl = null;
  let documentId = null;
  if (doc) {
    documentId = doc.id;
    const resolvedBlank = await resolveBlankTemplatePdf(doc);
    if (resolvedBlank) {
      pdfUrl = `data:${resolvedBlank.mimeType};base64,${resolvedBlank.buffer.toString('base64')}`;
    } else {
      pdfUrl = await getSignedUrl(doc.storage_path);
    }
  } else {
    // No filled doc yet — serve the blank 20-19 template so the preview pane
    // is never empty.
    const blank = await resolveBlankTemplatePdf({
      document_type: 'form_template',
      status: 'blank',
      form_template_id: null,
      _short_name_fallback: '1-4 Family Contract',
    });
    if (blank) {
      pdfUrl = `data:${blank.mimeType};base64,${blank.buffer.toString('base64')}`;
    }
  }

  // 6. Look up TREC 20-19 form_templates row for the version banner.
  let trecEffectiveDate = null;
  try {
    const tplRows = await supabaseCall(
      'GET',
      `form_templates?trec_number=eq.20-19&select=id,trec_effective_date&limit=1`
    );
    if (tplRows && tplRows[0]) trecEffectiveDate = tplRows[0].trec_effective_date || null;
  } catch (_err) {
    // Non-fatal — banner just shows form number without the date.
  }

  const versionLabel = trecEffectiveDate
    ? `TREC 20-19 · Effective ${formatDateMDY(trecEffectiveDate)}`
    : 'TREC 20-19';

  return res.status(200).json({
    ok: true,
    formNumber: '20-19',
    templateId: TREC_20_19_TEMPLATE_ID,
    trecFormNumber: '20-19',
    trecEffectiveDate,
    versionLabel,
    transaction: {
      id: txn.id,
      buyer_name: txn.buyer_name || null,
      seller_name: txn.seller_name || null,
      property_address: txn.property_address || null,
      city_state_zip: txn.city_state_zip || null,
      role: txn.role || null,
    },
    pageCount: runRow.page_count || 12,
    pdfUrl,
    documentId,
    sections,
    totals: { total, required, filled, missing },
    unmappedCount,
  });
}

// YYYY-MM-DD -> MM/DD/YYYY
function formatDateMDY(iso) {
  if (!iso) return '';
  const parts = String(iso).slice(0, 10).split('-');
  if (parts.length !== 3) return String(iso);
  return `${parts[1]}/${parts[2]}/${parts[0]}`;
}

module.exports = async function handler(req, res) {
  applyCors(req, res);
  if (req.method === 'OPTIONS') return res.status(204).end();
  if (req.method !== 'POST') {
    res.setHeader('Allow', 'POST, OPTIONS');
    return res.status(405).json({ ok: false, error: 'Method not allowed.' });
  }

  try {
    const { userId } = await verifySupabaseToken(req);

    let body = req.body;
    if (typeof body === 'string') {
      try { body = JSON.parse(body); } catch { body = {}; }
    }
    body = body || {};

    const transactionId = sanitizeString(body.transaction_id, { maxLength: 200 });
    if (!transactionId) throw new ValidationError('transaction_id is required.');

    // Phase 1 Interactive Form Editor branch. When the caller passes
    // form_number: '20-19' (and only '20-19' for now), return the enriched
    // 219-field metadata layer for the progressive-disclosure editor.
    const formNumber = sanitizeString(body.form_number, { maxLength: 20 });
    if (formNumber === '20-19') {
      return handlePhase1Init({
        req,
        res,
        userId,
        transactionId,
      });
    }

    // Optionally restrict to a subset of forms.
    const requestedForms = Array.isArray(body.forms)
      ? body.forms.filter((f) => typeof f === 'string' && EDITABLE_FIELDS_BY_FORM[f])
      : Object.keys(EDITABLE_FIELDS_BY_FORM);

    // 1. Fetch the transaction row.
    const txnRows = await supabaseCall(
      'GET',
      `transactions?id=eq.${transactionId}&limit=1`
    );
    if (!txnRows || txnRows.length === 0) {
      return res.status(404).json({ ok: false, error: 'Transaction not found.' });
    }
    const txn = txnRows[0];
    if (txn.user_id !== userId) {
      return res.status(403).json({ ok: false, error: 'Forbidden.' });
    }

    // 2. Fetch the most recent filled_form document for each form type.
    // fill-form.js writes documents.document_type as one of
    //   resale_contract | financing_addendum | hoa_addendum | lead_paint_addendum
    // (and leaves the legacy form_type column NULL). We match on document_type.
    const wantedDocTypes = requestedForms
      .map((f) => FORM_TYPE_TO_DOCUMENT_TYPE[f])
      .filter(Boolean);
    const docTypeFilter = wantedDocTypes.length > 0
      ? `document_type=in.(${wantedDocTypes.map((t) => `"${t}"`).join(',')})`
      : `document_type=in.("resale_contract","financing_addendum","hoa_addendum","lead_paint_addendum")`;
    // 2026-07-13 CARTER — SELECT widened to include status + form_template_id
    // so blank template docs can be served to the editor via data URL instead
    // of a broken signed URL.
    const docRows = await supabaseCall(
      'GET',
      `documents?transaction_id=eq.${transactionId}&${docTypeFilter}&select=id,document_type,storage_path,created_at,file_name,status,form_template_id&order=created_at.desc`
    );

    // Latest-per-document_type -> map back to form_type key.
    const latestDocByFormType = {};
    for (const d of (docRows || [])) {
      if (!d.document_type) continue;
      // Reverse-map document_type -> form_type key.
      const formTypeKey = Object.keys(FORM_TYPE_TO_DOCUMENT_TYPE)
        .find((k) => FORM_TYPE_TO_DOCUMENT_TYPE[k] === d.document_type);
      if (!formTypeKey) continue;
      if (!latestDocByFormType[formTypeKey]) {
        latestDocByFormType[formTypeKey] = d;
      }
    }

    // 3. Build per-form response.
    const forms = {};
    for (const formType of requestedForms) {
      const editableFields = EDITABLE_FIELDS_BY_FORM[formType] || [];
      const doc = latestDocByFormType[formType] || null;
      // 2026-07-13 CARTER — For blank form_template docs, storage_path is a
      // placeholder ("template/{id}.pdf") that 404s from Storage. Serve the
      // PDF as a data URL from the bundled base64 asset instead. pdfjsLib in
      // PdfViewer.jsx accepts data URLs the same as signed URLs.
      let signedUrl = null;
      if (doc) {
        const resolvedBlank = await resolveBlankTemplatePdf(doc);
        if (resolvedBlank) {
          signedUrl = `data:${resolvedBlank.mimeType};base64,${resolvedBlank.buffer.toString('base64')}`;
          console.log(`[interactive-editor-init] Blank template ${doc.id} served as data URL (${resolvedBlank.buffer.length} bytes).`);
        } else {
          signedUrl = await getSignedUrl(doc.storage_path);
        }
      }

      // Phase 3: load coords + build a lookup by canonical friendly key.
      // Aliases collapse "friendlyKey_1" / "friendlyKey_2" (duplicates in
      // the TREC field map) onto the API's canonical key (e.g. buyer_name).
      const KEY_ALIASES = {
        buyer_name_1: 'buyer_name',
        seller_name_1: 'seller_name',
        earnest_money_amount: 'earnest_money',
        property_city: 'city_state_zip',
      };
      const coordsDoc = loadCoords(formType);
      const coordsByKey = {};
      if (coordsDoc && Array.isArray(coordsDoc.fields)) {
        for (const w of coordsDoc.fields) {
          if (!w.key) continue;
          const canonical = KEY_ALIASES[w.key] || w.key;
          // First widget for a given key wins (later widgets may be
          // duplicate placements — e.g. footer names).
          if (!coordsByKey[canonical]) coordsByKey[canonical] = w;
        }
      }

      const fields = editableFields.map((f) => {
        const rawValue = txn[f.key];
        const valueStr = formatFieldValue(rawValue, f.type);
        const coordEntry = coordsByKey[f.key] || null;
        return {
          id: `${formType}:${f.key}`,
          form: formType,
          key: f.key,
          label: fieldNameToPrompt(f.key),
          value: valueStr,
          autoFilledValue: valueStr,
          type: f.type,
          required: f.required,
          valid: isFieldValid(rawValue, f.type, f.required),
          source: 'auto',
          // Phase 3 overlay coords (top-left origin, percent-of-page).
          // Null when the field key isn't mapped to a PDF widget yet.
          page: coordEntry ? coordEntry.page : null,
          x_pct: coordEntry ? coordEntry.x_pct : null,
          y_pct: coordEntry ? coordEntry.y_pct : null,
          w_pct: coordEntry ? coordEntry.w_pct : null,
          h_pct: coordEntry ? coordEntry.h_pct : null,
          pdf_field_name: coordEntry ? coordEntry.pdf_field_name : null,
        };
      });

      forms[formType] = {
        code: FORM_LABELS[formType]?.code || formType,
        name: FORM_LABELS[formType]?.name || formType,
        pdfUrl: signedUrl,
        documentId: doc?.id || null,
        fileName: doc?.file_name || null,
        available: Boolean(doc),
        fields,
        // Phase 3: page geometry so the client can align its canvas.
        pageCount: coordsDoc?.page_count || null,
        pageSizes: coordsDoc?.page_sizes || null,
      };
    }

    return res.status(200).json({
      ok: true,
      transaction: {
        id: txn.id,
        buyer_name: txn.buyer_name || null,
        seller_name: txn.seller_name || null,
        property_address: txn.property_address || null,
        city_state_zip: txn.city_state_zip || null,
        // 'buyer' when the current user represents the buyer side of the
        // deal, 'listing' when they represent the seller side. Drives the
        // party-assignment dropdown filter in the editor so buyer-side
        // deals never see seller options and vice versa.
        role: txn.role || null,
      },
      forms,
    });
  } catch (err) {
    if (err instanceof ValidationError) {
      return res.status(400).json({ ok: false, error: err.message });
    }
    if (err instanceof AuthError) {
      return res.status(err.status || 401).json({ ok: false, error: err.message });
    }
    console.error('[interactive-editor-init] error:', err && err.message);
    return res.status(500).json({ ok: false, error: 'Internal server error.' });
  }
};
