const COORDS_CACHE = {};
function loadCoords(formType) {
  if (COORDS_CACHE[formType]) return COORDS_CACHE[formType];
  const fname = COORDS_FILES[formType];
  if (!fname) return null;
  const p = path.join(__dirname, '_assets', fname);
  try {
    const raw = fs.readFileSync(p, 'utf8');
    const parsed = JSON.parse(raw);
    COORDS_CACHE[formType] = parsed;
    return parsed;
  } catch (err) {
    console.warn(`[interactive-editor-init] coords load failed for ${formType}: ${err.message}`);
    COORDS_CACHE[formType] = null;
    return null;
  }
}

