#!/usr/bin/env node
/**
 * scripts/generate-executed-block-index.js
 *
 * Build-time generator for api/_assets/executed-block-index.json
 * — part of the EXECUTED-date gate (api/_lib/executed-date-field-gate.js).
 *
 * Extracts REAL text from every blank PDF asset api/esign-create.js can
 * send (every Mode-A mapped form in api/_assets/esign-field-maps.json, plus
 * resale_contract's own asset) via pdftotext, and records whether that text
 * carries the TREC "EXECUTED the ___ day of ___, 20___ (Effective Date)"
 * paragraph. This is NOT a hand-maintained form-number list — rerun this
 * script any time a form asset changes (the committed esign-field-maps.json
 * regeneration already has a blank_pdf_sha256 pin per form; re-running this
 * alongside it keeps the index honest) and the result is read from the real
 * document, never guessed.
 *
 * Runs here (dev/CI), not inside api/esign-create.js at Vercel runtime,
 * because Vercel's Node serverless runtime cannot be relied on to carry
 * pdftotext/poppler. The committed JSON output is what the runtime reads —
 * see api/esign-create.js's loadExecutedBlockIndex().
 *
 * Usage:  node scripts/generate-executed-block-index.js
 *         node scripts/generate-executed-block-index.js --check   (verify only, exit 1 on drift)
 */

'use strict';

const fs = require('fs');
const path = require('path');
const os = require('os');
const { execFileSync } = require('child_process');

const REPO = path.resolve(__dirname, '..');
// Deliberately NOT under api/_assets/field-maps/ — that directory is scanned
// wholesale by scripts/regression-esign-field-maps.js's Barry Whyte gate,
// which assumes every file there is a flat {fields:{...}} DocuSeal map. This
// index has a different shape and lives one level up, next to
// esign-field-maps.json.
const OUT_FILE = path.join(REPO, 'api', '_assets', 'executed-block-index.json');

// Same detection the runtime gate uses — imported, not duplicated, so the
// generator's scan and api/_lib/executed-date-field-gate.js's own
// hasExecutedBlock() can never drift apart. This module is pure (no
// Supabase/network/esign-create.js requires), so it is safe to pull in here.
const { hasExecutedBlock: textHasExecutedBlock } = require(
  path.join(__dirname, '..', 'api', '_lib', 'executed-date-field-gate'),
);

function findPdftotext() {
  const candidates = [
    '/home/heath/.local/bin/pdftotext',
    '/usr/bin/pdftotext',
    '/usr/local/bin/pdftotext',
    'pdftotext',
  ];
  for (const c of candidates) {
    try {
      execFileSync(c, ['-v'], { stdio: 'ignore' });
      return c;
    } catch (e) { /* try next */ }
  }
  return null;
}

function b64From(modPath) {
  const mod = require(modPath);
  return typeof mod === 'string' ? mod : (mod && (mod.base64Pdf || mod.base64)) || null;
}

function scanAsset(pdftotextBin, assetModule) {
  const modPath = path.join(REPO, 'api', '_assets', assetModule);
  const b64 = b64From(modPath);
  if (!b64) throw new Error(`${assetModule}: no base64 export found`);
  const tmp = path.join(os.tmpdir(), `executed-block-scan-${process.pid}.pdf`);
  fs.writeFileSync(tmp, Buffer.from(b64, 'base64'));
  try {
    const text = execFileSync(pdftotextBin, [tmp, '-'], { encoding: 'utf8', maxBuffer: 1024 * 1024 * 20 });
    return textHasExecutedBlock(text);
  } finally {
    fs.unlinkSync(tmp);
  }
}

function main() {
  const check = process.argv.includes('--check');
  const pdftotextBin = findPdftotext();
  if (!pdftotextBin) {
    console.error('ERROR: pdftotext (poppler-utils) not found. Install it to regenerate this index.');
    process.exit(1);
  }

  const fieldMaps = require(path.join(REPO, 'api', '_assets', 'esign-field-maps.json'));
  const forms = {};
  const problems = [];

  // Every Mode-A mapped form (api/_assets/esign-field-maps.json).
  for (const [formType, entry] of Object.entries(fieldMaps.forms || {})) {
    try {
      forms[formType] = scanAsset(pdftotextBin, entry.asset_module);
    } catch (err) {
      problems.push(`${formType}: ${err.message}`);
    }
  }

  // resale_contract has its own blank asset, outside esign-field-maps.json
  // (api/esign-create.js's resaleFormEntry()).
  try {
    forms.resale_contract = scanAsset(pdftotextBin, 'trec-resale-20-19-base64.js');
  } catch (err) {
    problems.push(`resale_contract: ${err.message}`);
  }

  if (problems.length) {
    console.error('Problems scanning assets:\n' + problems.map((p) => `  - ${p}`).join('\n'));
    process.exit(1);
  }

  const output = {
    _readme: 'Generated by scripts/generate-executed-block-index.js. Do not hand-edit — rerun the '
      + 'generator instead, so a form revision is caught by scanning the real PDF, not by someone '
      + 'remembering to update this file.',
    generated_at: new Date().toISOString(),
    forms,
  };

  const hasBlock = Object.entries(forms).filter(([, v]) => v).map(([k]) => k);
  console.log(`[generate-executed-block-index] ${Object.keys(forms).length} forms scanned. `
    + `EXECUTED block found on: ${hasBlock.join(', ') || '(none)'}`);

  if (check) {
    const existing = fs.existsSync(OUT_FILE) ? JSON.parse(fs.readFileSync(OUT_FILE, 'utf8')) : null;
    const drift = !existing || JSON.stringify(existing.forms) !== JSON.stringify(forms);
    if (drift) {
      console.error('[generate-executed-block-index] DRIFT — committed index does not match a fresh scan. '
        + 'Run without --check to regenerate.');
      process.exit(1);
    }
    console.log('[generate-executed-block-index] committed index matches a fresh scan. OK.');
    return;
  }

  fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
  fs.writeFileSync(OUT_FILE, JSON.stringify(output, null, 2) + '\n');
  console.log(`[generate-executed-block-index] wrote ${OUT_FILE}`);
}

main();
