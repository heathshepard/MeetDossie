#!/usr/bin/env node
/**
 * scripts/build-txr-1406-packet.js
 *
 * Productized, reusable builder for the Texas REALTORS TXR-1406 Seller's
 * Disclosure Notice DocuSeal packet. Replaces the throwaway one-off at
 * .tmp/nopalito-disclosure-resend/build-1406-fixed-VERIFIED-2026-09-27.js —
 * same verified logic, committed, deal-agnostic (no hardcoded names/address).
 *
 * TXR-1406 does not fit the Mode-A role-map pipeline used by the other 23
 * forms in api/_assets/esign-field-maps.json: on a Mode-A form everything
 * except the party's signature/initials/date is DEAL DATA Dossie already
 * has and bakes into the PDF before send, so only signing widgets go to
 * DocuSeal. TXR-1406's ~250-item Y/N/U disclosure grid is the opposite —
 * it is the seller's own knowledge, answered live at signing, not data
 * Dossie holds in advance. So the full content grid must ship to DocuSeal
 * as live fillable widgets, not be excluded/baked. This form is deliberately
 * NOT registered in api/_assets/esign-field-maps.json (that file is
 * generated by scripts/build-esign-field-maps.js strictly from the Mode-A
 * role-map convention — forcing TXR-1406 through it would silently DROP the
 * disclosure content fields, which is worse than either defect this script
 * fixes). This script + its two field-map assets are TXR-1406's own,
 * parallel pipeline:
 *   - api/_assets/txr-1406-sellers-disclosure-base64.js   (genuinely blank
 *     asset — verified via pdftotext that NO page, including page 1, carries
 *     any address; the "BLANK" zipForm pull this replaced had the Nopalito
 *     address baked into page 1 by zipForm's own mail-merge, which is why
 *     the old build worked on page 1 and nowhere else)
 *   - api/_assets/field-maps/txr-1406-address-coords.json  (Defect 1 fix —
 *     bakes "Concerning the Property at <address>" as real PDF text on
 *     EVERY page, 1-7; the form has zero AcroForm fields for this line)
 *   - api/_assets/field-maps/txr-1406-sellers-disclosure-docuseal-fields.json
 *     (Defect 2 fix baked in — corrected per-page seller-initials position,
 *     verified against the real footer line, plus two pre-existing cosmetic
 *     fixes: Section 11 report-count overlap, page-6 signature-box overlap)
 *
 * `required` is computed centrally via api/_lib/esign-field-required-policy.js
 * (dsFieldRequired) — never hardcoded — with 'sellers-disclosure-txr-1406' in
 * INITIALS_REQUIRED_FORMS per Heath's "all initials are required" rule.
 *
 * Usage:
 *   node scripts/build-txr-1406-packet.js --address "23 Nopalito, San Antonio, TX 78261" \
 *     --seller1 "Barry Whyte" --seller1-email heath.shepard@kw.com \
 *     [--seller2 "Jennifer Whyte" --seller2-email heath.shepard@kw.com] \
 *     [--template-name "..."] [--out /path/to/dir]
 *
 * Safety: send_email is ALWAYS false — this only ever creates a submission
 * with slug links this script prints; it never emails a real party. Never
 * pass a non-test address to real client emails without Heath's go-ahead.
 */

'use strict';

const fs = require('fs');
const path = require('path');
const os = require('os');
const { execFileSync } = require('child_process');
const { PDFDocument, rgb, StandardFonts } = require('pdf-lib');

const { dsFieldRequired } = require('../api/_lib/esign-field-required-policy');
const {
  hasExecutedBlock,
  checkExecutedDateFieldAssignment,
} = require('../api/_lib/executed-date-field-gate');

// pdftotext on the actual baked PDF bytes about to be sent — "detect from
// the document itself" (api/_lib/executed-date-field-gate.js), not a
// hardcoded form-number check.
function extractPdfText(pdfBytes) {
  const tmp = path.join(os.tmpdir(), `txr-1406-executed-scan-${process.pid}.pdf`);
  fs.writeFileSync(tmp, pdfBytes);
  try {
    return execFileSync('pdftotext', [tmp, '-'], { encoding: 'utf8', maxBuffer: 1024 * 1024 * 20 });
  } finally {
    fs.unlinkSync(tmp);
  }
}

const DOCUSEAL_API_KEY =
  process.env.DOCUSEAL_API_KEY ||
  (fs.existsSync(path.join(__dirname, '..', '.env.local'))
    ? (fs.readFileSync(path.join(__dirname, '..', '.env.local'), 'utf8')
        .replace(/^﻿/, '')
        .match(/DOCUSEAL_API_KEY="?([^"\n]+)"?/) || [])[1]
    : null);

if (!DOCUSEAL_API_KEY) {
  console.error('ERROR: DOCUSEAL_API_KEY not found (env or .env.local)');
  process.exit(1);
}

const DOCUSEAL_BASE = 'https://api.docuseal.com';
const FORM_TYPE = 'sellers-disclosure-txr-1406';
const PW = 612;
const PH = 792;

function parseArgs(argv) {
  const out = { outDir: path.join(__dirname, '..', '.tmp', 'txr-1406-packet-out') };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === '--address') out.address = argv[++i];
    else if (a === '--seller1') out.seller1Name = argv[++i];
    else if (a === '--seller1-email') out.seller1Email = argv[++i];
    else if (a === '--seller2') out.seller2Name = argv[++i];
    else if (a === '--seller2-email') out.seller2Email = argv[++i];
    else if (a === '--template-name') out.templateName = argv[++i];
    else if (a === '--out') out.outDir = argv[++i];
  }
  return out;
}

// Defect 1 fix — bake the property address on every page (1-7). This form
// has zero AcroForm fields for it; per acroform-field-names-lie method,
// coordinates were read from the real rendered page (pdftotext -bbox), not
// guessed. Bottom-origin y for pdf-lib = PH - topOriginBaseline.
async function bakeAddress(address) {
  const { base64Pdf } = require('../api/_assets/txr-1406-sellers-disclosure-base64.js');
  const coordsPath = path.join(__dirname, '..', 'api', '_assets', 'field-maps', 'txr-1406-address-coords.json');
  const coords = JSON.parse(fs.readFileSync(coordsPath, 'utf8'));

  const doc = await PDFDocument.load(Buffer.from(base64Pdf, 'base64'), { ignoreEncryption: true });
  const font = await doc.embedFont(StandardFonts.Helvetica);
  const fontBold = await doc.embedFont(StandardFonts.HelveticaBold);
  const pages = doc.getPages();

  for (const [key, spec] of Object.entries(coords.fields)) {
    const page = pages[spec.page - 1];
    if (!page) throw new Error(`bakeAddress: no page ${spec.page} for ${key}`);
    page.drawText(address, {
      x: spec.x,
      y: PH - spec.y,
      size: spec.font_size,
      font: spec.bold ? fontBold : font,
      color: rgb(0, 0, 0),
    });
  }
  return doc.save();
}

function toArea(a, page) {
  return {
    x: +(a.x / PW).toFixed(6),
    y: +(a.y / PH).toFixed(6),
    w: +(a.w / PW).toFixed(6),
    h: +(a.h / PH).toFixed(6),
    page,
  };
}

function resolveRole(f, opts) {
  if (f.role === 'Seller 1') return { role: 'Seller 1', name: opts.seller1Name, email: opts.seller1Email };
  if (f.role === 'Seller 2') return { role: 'Seller 2', name: opts.seller2Name, email: opts.seller2Email };
  throw new Error(`Unknown role "${f.role}" on field ${f.name}`);
}

// Defect 2 fix (+ Section 11 / page 6 cosmetic fixes) already baked into the
// committed field-map; this just converts to DocuSeal's wire shape and
// computes `required` centrally (never trusts a stored value — same rule as
// api/esign-create.js's dsFieldRequired() call sites, per the Barry Whyte
// incident review).
function buildDsFields(fieldList, opts) {
  const seenRoles = new Set();
  return fieldList.map((f) => {
    const r = resolveRole(f, opts);
    seenRoles.add(r.role);
    const base = {
      name: f.name,
      type: f.type,
      role: r.role,
      required: dsFieldRequired(f.type, FORM_TYPE),
    };
    if (f.type === 'radio') {
      base.areas = f.options.map((o) => ({ ...toArea(o, f.page), option: o.value }));
    } else {
      base.areas = [toArea(f, f.page)];
    }
    return base;
  });
}

async function main() {
  const opts = parseArgs(process.argv.slice(2));
  if (!opts.address) throw new Error('--address is required');
  if (!opts.seller1Name || !opts.seller1Email) throw new Error('--seller1 and --seller1-email are required');
  fs.mkdirSync(opts.outDir, { recursive: true });

  console.log(`[txr-1406] baking address "${opts.address}" onto all 7 pages...`);
  const bakedBytes = await bakeAddress(opts.address);
  const bakedPath = path.join(opts.outDir, 'txr-1406-address-baked.pdf');
  fs.writeFileSync(bakedPath, bakedBytes);
  console.log(`[txr-1406] baked PDF -> ${bakedPath}`);

  const fieldMapPath = path.join(__dirname, '..', 'api', '_assets', 'field-maps', 'txr-1406-sellers-disclosure-docuseal-fields.json');
  const { fields } = JSON.parse(fs.readFileSync(fieldMapPath, 'utf8'));
  const docFields = buildDsFields(fields, opts);
  const initialsRequired = dsFieldRequired('initials', FORM_TYPE);
  console.log(`[txr-1406] ${docFields.length} DocuSeal fields built. initials required=${initialsRequired}`);

  const submitters = [{ role: 'Seller 1', name: opts.seller1Name, email: opts.seller1Email }];
  if (opts.seller2Name && opts.seller2Email) {
    submitters.push({ role: 'Seller 2', name: opts.seller2Name, email: opts.seller2Email });
  }

  // EXECUTED (Effective Date) gate — api/_lib/executed-date-field-gate.js.
  // TXR-1406 is a disclosure notice, not an agreement — it has no acceptance
  // to date and should pass through untouched (confirmed by scanning the
  // real baked PDF text, not assumed). Runs here anyway, on every build, so
  // the day this form (or a future one this script is adapted to build)
  // actually does carry the paragraph, the gate catches it instead of
  // silently shipping blank.
  const execCheck = checkExecutedDateFieldAssignment({
    formLabel: `TXR-1406 Seller's Disclosure — ${opts.address}`,
    hasExecutedBlock: hasExecutedBlock(extractPdfText(bakedBytes)),
    fields: docFields,
    signers: submitters,
    signingOrder: 'preserved',
  });
  if (!execCheck.ok) {
    throw new Error(execCheck.error);
  }

  const H = { 'X-Auth-Token': DOCUSEAL_API_KEY, 'Content-Type': 'application/json' };
  const tRes = await fetch(`${DOCUSEAL_BASE}/templates/pdf`, {
    method: 'POST',
    headers: H,
    body: JSON.stringify({
      name: opts.templateName || `TXR-1406 Seller's Disclosure — ${opts.address}`,
      documents: [{
        name: "Seller's Disclosure Notice (TXR-1406).pdf",
        file: Buffer.from(bakedBytes).toString('base64'),
        fields: docFields,
      }],
    }),
  });
  const template = await tRes.json();
  if (!template.id) throw new Error(`template create failed ${tRes.status}: ${JSON.stringify(template).slice(0, 2000)}`);
  console.log(`[txr-1406] template id ${template.id}`);

  const sRes = await fetch(`${DOCUSEAL_BASE}/submissions`, {
    method: 'POST',
    headers: H,
    body: JSON.stringify({
      template_id: template.id,
      send_email: false, // never emails a real party — caller completes via the printed slug link
      order: 'preserved',
      submitters,
    }),
  });
  const sent = await sRes.json();
  const sentList = Array.isArray(sent) ? sent : sent.submitters || [];
  if (!sentList.length) throw new Error(`submission create failed ${sRes.status}: ${JSON.stringify(sent).slice(0, 2000)}`);

  console.log(`[txr-1406] submission created. template_id=${template.id}`);
  for (const s of sentList) console.log(`  role=${s.role} slug=${s.slug} email=${s.email}`);

  const resultPath = path.join(opts.outDir, 'submission-create.json');
  fs.writeFileSync(resultPath, JSON.stringify({ template_id: template.id, submitters: sentList }, null, 2));
  console.log(`[txr-1406] result -> ${resultPath}`);
}

if (require.main === module) {
  main().catch((e) => { console.error('FAILED', (e && e.stack) || e); process.exit(1); });
}

module.exports = { bakeAddress, buildDsFields, FORM_TYPE, extractPdfText };
